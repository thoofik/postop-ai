type Key = keyof (typeof copy)["en"];

const Ctx = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: (key: Key) => string }>({
  lang: "en",
  setLang: () => undefined,
  t: (key) => copy.en[key],
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem("postop-lang") as Lang) || "en");
  const value = useMemo(
    () => ({
      lang,
      setLang: (next: Lang) => {
        localStorage.setItem("postop-lang", next);
        setLang(next);
      },
      t: (key: Key) => copy[lang][key],
    }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}

export function speechLang(lang: Lang) {
  return LANGS.find((item) => item.id === lang)?.speech ?? "en-IN";
}
